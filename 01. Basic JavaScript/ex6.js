// Learning DataType puring in JavaScript

let a = 10;
console.log("Value of a:", a.toString()); // Convert number to string

let b = "20";
console.log("Value of b:", Number(b)); // Convert string to number

let c = 10.5;
console.log("Value of c:", parseInt(c)); // Convert float to integer

let d = "15.75";
console.log("Value of d:", parseFloat(d)); // Convert string to float

let e = 10.456789;
console.log("Value of e:", e.toFixed(2)); // Convert number to string with 2 decimal places 
console.log("Value of e", Math.round(e)); // Round the number to the nearest integer    